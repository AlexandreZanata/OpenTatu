//! `benchmark/results/<AUDIT>.json` (one run) and `benchmark/SCOREBOARD.md` (every run,
//! per prompt version and per model). English: a development record, like the docs.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use opentatu_core::{AuditId, CommitHash, Timestamp, UsageTotals};
use serde::{Deserialize, Serialize};

use crate::{PipelineCounts, Score};

/// One benchmark run.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct RunResult {
    /// Benchmark name.
    pub benchmark: String,
    /// Release tag.
    pub revision: String,
    /// Upstream commit the known flaws come from.
    pub upstream_commit: CommitHash,
    /// The FULL audit of the run.
    pub audit_id: AuditId,
    /// Its final status.
    pub status: String,
    /// When it ended (clock).
    pub completed_at: Option<Timestamp>,
    /// Its duration.
    pub duration_seconds: Option<i64>,
    /// Model per AI role (from `audit.json`).
    pub models: BTreeMap<String, String>,
    /// `name -> version` of the prompts (from `audit.json`).
    pub prompt_versions: BTreeMap<String, String>,
    /// Model usage.
    pub usage: UsageTotals,
    /// Command-line role overrides used, if any (`role=model`).
    pub overrides: Vec<String>,
    /// The score.
    pub score: Score,
    /// What the verifier and the skeptic decided.
    #[serde(default)]
    pub pipeline: PipelineCounts,
}

impl RunResult {
    /// The configuration this run measures: prompt versions and model per role.
    fn configuration(&self) -> String {
        let prompts: Vec<String> = self
            .prompt_versions
            .iter()
            .filter(|(name, _)| name.as_str() != "base")
            .map(|(name, version)| format!("{name}@{version}"))
            .collect();
        let models: Vec<String> = self
            .models
            .iter()
            .map(|(role, model)| format!("{role}={model}"))
            .collect();
        format!(
            "base@{} · {} · {}",
            self.prompt_versions.get("base").map_or("?", String::as_str),
            prompts.join(" "),
            models.join(" ")
        )
    }
}

fn percent(value: f64) -> String {
    format!("{:.0}%", value * 100.0)
}

/// `benchmark/SCOREBOARD.md` from every run, oldest first.
pub fn render_scoreboard(results: &[RunResult]) -> String {
    let mut md = String::from(
        "# Benchmark scoreboard\n\n\
         Generated by `opentatu benchmark run` / `opentatu benchmark scoreboard` from\n\
         `benchmark/results/*.json` — do not edit by hand. How it works:\n\
         [benchmark/README.md](README.md) and ADR-0031.\n\n\
         - **Found**: known flaws matched by a reported finding (confirmed, not dismissed).\n\
         - **Hypothesis only**: matched only by a hypothesis that was not reported.\n\
         - **Outside the list**: reported findings that match no known flaw — the false-positive\n  \
         candidates. Apps mark only part of their flaws (Juice Shop marks its coding\n  \
         challenges, not every challenge), so many of these are real: review them before\n  \
         calling them false positives.\n\
         - Recall = found / known; list precision = reported findings that match / reported.\n",
    );
    let mut by_benchmark: BTreeMap<&str, Vec<&RunResult>> = BTreeMap::new();
    for result in results {
        by_benchmark
            .entry(result.benchmark.as_str())
            .or_default()
            .push(result);
    }
    for (benchmark, runs) in by_benchmark {
        let first = runs[0];
        let _ = write!(
            md,
            "\n## {benchmark} {} (`{}`)\n\n\
             | Run | Status | Found | Hypothesis only | Missed | Outside the list | Recall | List precision | Calls | Cost (US$) | Duration |\n\
             |---|---|---|---|---|---|---|---|---|---|---|\n",
            first.revision,
            first.upstream_commit.short()
        );
        for run in &runs {
            let score = &run.score;
            let _ = writeln!(
                md,
                "| [{id}](results/{id}.json) | {} | {}/{} | {} | {} | {} | {} | {} | {} | {:.3} | {} |",
                run.status,
                score.found.len(),
                score.expected,
                score.hypothesized_only.len(),
                score.missed.len(),
                score.false_positives.len(),
                percent(score.recall),
                percent(score.precision),
                run.usage.calls,
                run.usage.cost_usd,
                run.duration_seconds
                    .map_or_else(|| "—".to_owned(), opentatu_core::duration_label),
                id = run.audit_id,
            );
        }
        md.push_str("\n### Pipeline per run\n\n| Run | Hypotheses | Confirmed | Dismissed by verifier | Inconclusive | Not verified | Dismissed by skeptic | Downgraded by skeptic | Overrides |\n|---|---|---|---|---|---|---|---|---|\n");
        for run in &runs {
            let p = &run.pipeline;
            let _ = writeln!(
                md,
                "| {} | {} | {} | {} | {} | {} | {} | {} | {} |",
                run.audit_id,
                p.hypotheses,
                p.confirmed,
                p.dismissed_by_verifier,
                p.inconclusive,
                p.not_verified,
                p.dismissed_by_skeptic,
                p.downgraded_by_skeptic,
                if run.overrides.is_empty() {
                    "—".to_owned()
                } else {
                    run.overrides.join(", ")
                }
            );
        }
        md.push_str("\n### Per prompt version and model\n\n| Configuration | Runs | Mean recall | Mean list precision |\n|---|---|---|---|\n");
        let mut by_configuration: BTreeMap<String, Vec<&RunResult>> = BTreeMap::new();
        for run in &runs {
            by_configuration
                .entry(run.configuration())
                .or_default()
                .push(run);
        }
        for (configuration, group) in by_configuration {
            let mean = |pick: fn(&Score) -> f64| {
                group.iter().map(|r| pick(&r.score)).sum::<f64>() / group.len() as f64
            };
            let _ = writeln!(
                md,
                "| {configuration} | {} | {} | {} |",
                group.len(),
                percent(mean(|s| s.recall)),
                percent(mean(|s| s.precision))
            );
        }
        md.push_str("\n### Known flaws by category (latest run)\n\n| Category | Known | Found |\n|---|---|---|\n");
        if let Some(latest) = runs.last() {
            let mut categories: BTreeMap<&str, (usize, usize)> = BTreeMap::new();
            let all = latest
                .score
                .found
                .iter()
                .map(|m| (m, true))
                .chain(latest.score.hypothesized_only.iter().map(|m| (m, false)))
                .chain(latest.score.missed.iter().map(|m| (m, false)));
            for (flaw, found) in all {
                let entry = categories.entry(flaw.category.as_str()).or_default();
                entry.0 += 1;
                entry.1 += usize::from(found);
            }
            for (category, (known, found)) in categories {
                let _ = writeln!(md, "| {category} | {known} | {found} |");
            }
        }
    }
    md
}

#[cfg(test)]
mod tests {
    use opentatu_core::FindingState;

    use super::*;
    use crate::score::tests::{expected, finding};

    fn run(audit: &str, skeptic: &str) -> RunResult {
        let findings = [finding(1, "routes/login.ts", "34", FindingState::Upheld)];
        RunResult {
            benchmark: "demo".into(),
            revision: "v1".into(),
            upstream_commit: "266448aba68cd8ba5915f526a128da4fa7bc3f9f".parse().unwrap(),
            audit_id: audit.parse().unwrap(),
            status: "PARTIAL".into(),
            completed_at: None,
            duration_seconds: Some(125),
            models: BTreeMap::from([
                ("hunter".into(), "deepseek-v4.1-flash".into()),
                ("skeptic".into(), skeptic.into()),
            ]),
            prompt_versions: BTreeMap::from([
                ("base".into(), "1.1.0".into()),
                ("hunter".into(), "2.1.0".into()),
            ]),
            usage: UsageTotals {
                calls: 10,
                input_tokens: 1,
                output_tokens: 1,
                cost_usd: 0.25,
            },
            overrides: vec!["budget.FULL.max_tokens=10000000".into()],
            pipeline: crate::pipeline_counts(&findings, &[]),
            score: crate::score(&expected(), &findings, &[], 3),
        }
    }

    #[test]
    fn scoreboard_has_runs_configurations_and_categories() {
        let md = render_scoreboard(&[
            run(
                "AUD-BENCH-DEMO-1-20261112-1500",
                "muse-spark-1.3-contributor",
            ),
            run("AUD-BENCH-DEMO-2-20261112-1600", "deepseek-v4.1-flash"),
        ]);
        assert!(md.contains("## demo v1 (`266448a"), "{md}");
        assert!(md.contains(
            "| [AUD-BENCH-DEMO-1-20261112-1500](results/AUD-BENCH-DEMO-1-20261112-1500.json) | PARTIAL | 1/3 | 0 | 2 | 0 | 33% | 100% | 10 | 0.250 |"
        ), "{md}");
        assert_eq!(
            md.matches("base@1.1.0 · hunter@2.1.0").count(),
            2,
            "one row per model configuration"
        );
        assert!(md.contains("| Injection | 3 | 1 |"));
        assert!(md.contains("| 0 | 0 | 0 | 0 | 0 | 0 | 0 | budget.FULL.max_tokens=10000000 |"));
    }
}
